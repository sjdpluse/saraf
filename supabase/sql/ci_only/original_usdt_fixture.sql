CREATE TABLE public.user_profiles(
 chat_id bigint PRIMARY KEY,
 first_name text,last_name text,phone text,kyc_status text NOT NULL DEFAULT 'pending',
 id_document_path text,selfie_path text,restricted_reason text,
 cancelled_orders integer NOT NULL DEFAULT 0,
 payment_info_change_count integer NOT NULL DEFAULT 0,
 successful_orders integer NOT NULL DEFAULT 0
);
CREATE TABLE public.usdt_quotes(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 chat_id bigint NOT NULL,order_type text NOT NULL,asset text NOT NULL,
 usdt_amount numeric NOT NULL,usd_rate numeric NOT NULL,fee_percent numeric NOT NULL DEFAULT 0,
 total_afn numeric NOT NULL,total_usd numeric NOT NULL,
 status text NOT NULL DEFAULT 'active', expires_at timestamptz NOT NULL,
 consumed_at timestamptz, pricing_model text,
 market_margin_usd numeric,supplier_profit_usd numeric,saraf_profit_usd numeric,
 customer_discount_usd numeric,supplier_payout_usd numeric,market_price_usd numeric,
 supplier_profit_afn numeric,saraf_profit_afn numeric,customer_discount_afn numeric,
 supplier_payout_afn numeric,market_price_afn numeric
);
CREATE TABLE public.usdt_orders(
 id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 chat_id bigint NOT NULL,username text,full_name text,phone text,
 order_type text NOT NULL,asset text NOT NULL,usdt_amount numeric NOT NULL,
 usd_rate numeric NOT NULL,fee_percent numeric,total_afn numeric NOT NULL,total_usd numeric NOT NULL,
 payment_method text,receive_method text,exchange_name text,network text,wallet_address text,
 receipt_file_id text,tx_proof text,bank_info text,status text NOT NULL DEFAULT 'pending',confirmed_at timestamptz,
 source text,risk_level text,risk_reasons text,idempotency_key text,quote_id bigint,
 in_person_code text,pricing_model text,
 market_margin_usd numeric,supplier_profit_usd numeric,saraf_profit_usd numeric,
 customer_discount_usd numeric,supplier_payout_usd numeric,market_price_usd numeric,
 supplier_profit_afn numeric,saraf_profit_afn numeric,customer_discount_afn numeric,
 supplier_payout_afn numeric,market_price_afn numeric
);
CREATE UNIQUE INDEX usdt_orders_chat_id_idempotency_key_uidx ON public.usdt_orders(chat_id,idempotency_key)
WHERE idempotency_key IS NOT NULL;
CREATE TABLE public.usdt_order_status_history(
 id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 order_id bigint NOT NULL,from_status text,to_status text NOT NULL,
 changed_by bigint,reason text
);
CREATE TABLE public.audit_log(
 id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 actor bigint,action text NOT NULL,entity text NOT NULL,
 entity_id text,after jsonb
);

CREATE TABLE public.remittance_orders(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 chat_id bigint NOT NULL,idempotency_key text NOT NULL,sender_country text NOT NULL,
 sender_name text,sender_phone text,beneficiary_full_name text NOT NULL,
 beneficiary_phone text NOT NULL,beneficiary_province text NOT NULL,
 beneficiary_city text NOT NULL,beneficiary_address text,
 beneficiary_id_document_path text,relationship text,purpose text,
 asset text NOT NULL,network text NOT NULL,
 crypto_amount numeric NOT NULL,usd_rate numeric NOT NULL,
 gross_afn numeric NOT NULL,fee_percent numeric NOT NULL,
 fee_afn numeric NOT NULL,payout_afn numeric NOT NULL,
 deposit_wallet text NOT NULL,pickup_code text,
 status text NOT NULL DEFAULT 'awaiting_transfer',
 verification_status text NOT NULL DEFAULT 'not_submitted',
 tx_hash text,updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX remittance_orders_chat_id_idempotency_key_key
 ON public.remittance_orders(chat_id,idempotency_key);
CREATE UNIQUE INDEX remittance_orders_tx_hash_unique_idx
 ON public.remittance_orders(lower(tx_hash)) WHERE tx_hash IS NOT NULL;
CREATE TABLE public.remittance_status_history(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 order_id bigint NOT NULL,from_status text,to_status text NOT NULL,
 changed_by bigint,note text
);

CREATE TABLE public.users(
 chat_id bigint PRIMARY KEY,is_active boolean NOT NULL DEFAULT true
);
CREATE TABLE public.spread_settings(
 currency text PRIMARY KEY,spread_percent numeric NOT NULL DEFAULT 1,
 updated_at timestamptz NOT NULL DEFAULT now()
);
