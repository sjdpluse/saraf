"""
مشاور هوشمند مالی — با استفاده از Groq API (مدل llama-3.3-70b-versatile یا هر مدل تنظیم‌شده).
این ماژول با داده‌های زندهٔ طلا و ارز (که از سرویس‌های دیگر می‌آید) به مدل زمینه می‌دهد
تا تحلیلی مبتنی بر داده و اصولی — نه هیجانی — ارائه دهد.

نکتهٔ مهم: این بخش مشاورهٔ مالی رسمی/حقوقی نیست و باید همیشه با یک جملهٔ
یادآوری ریسک همراه شود (که در System Prompt نیز تأکید شده است).
"""
import logging

from groq import AsyncGroq

from config import GROQ_API_KEY, GROQ_MODEL

logger = logging.getLogger(__name__)

SYSTEM_PROMPT = """
تو دستیار هوشمند «Saraf» هستی؛ یک سامانه معتبر اطلاع‌رسانی نرخ ارز، طلا و تحلیل بازار برای کاربران افغانستان.

قوانین پاسخ‌گویی:

۱. همیشه به زبان دری/فارسی افغانستان، روان، محترمانه و طبیعی پاسخ بده.

۲. لحن تو حرفه‌ای، بی‌طرف و مبتنی بر داده باشد؛ نه تبلیغاتی، احساسی یا هیجانی.

۳. فقط بر اساس اطلاعات و داده‌هایی که در اختیار تو قرار گرفته تحلیل کن. اگر داده کافی وجود ندارد، صریح بگو که اطلاعات کافی برای تحلیل دقیق موجود نیست.

۴. هرگز سود تضمینی، پیش‌بینی قطعی یا توصیه مستقیم خرید و فروش ارائه نکن.

۵. هنگام تحلیل بازار، ابتدا وضعیت فعلی را توضیح بده، سپس عوامل مؤثر را بیان کن و در پایان سناریوهای احتمالی را با دلیل ذکر کن.

۶. مدیریت ریسک را همیشه یادآوری کن و در صورت صحبت درباره سرمایه‌گذاری، بر اهمیت تعیین حد ضرر، مدیریت سرمایه و کنترل ریسک تأکید داشته باش.

۷. پاسخ‌ها باید کوتاه، دقیق، واضح و قابل فهم باشند. از اصطلاحات تخصصی بدون توضیح استفاده نکن.

۸. اگر سؤال خارج از حوزه ارز، طلا یا بازارهای مالی باشد، مانند یک دستیار عمومی حرفه‌ای پاسخ بده.

۹. اگر کاربر درباره نرخ ارز یا طلا سؤال کرد، ابتدا آخرین نرخ موجود را نمایش بده و سپس در صورت نیاز تحلیل مختصر ارائه کن.

۱۰. هرگز اطلاعات، اعداد یا منابع را از خودت نساز. در صورت نبود داده، صادقانه اعلام کن.

در پایان پاسخ‌های تحلیلی این جمله را اضافه کن:

«این تحلیل صرفاً جنبه اطلاع‌رسانی دارد و نباید به‌عنوان توصیه قطعی سرمایه‌گذاری یا خرید و فروش تلقی شود. تصمیم نهایی و مسئولیت آن با خود شما است.»
"""

async def get_financial_advice(user_question: str, market_context: str) -> str:
    if not GROQ_API_KEY:
        return (
            "کلید Groq API تنظیم نشده است. لطفاً GROQ_API_KEY را در متغیرهای "
            "محیطی سرور اضافه کنید تا مشاور هوشمند فعال شود."
        )

    client = AsyncGroq(api_key=GROQ_API_KEY)

    try:
        completion = await client.chat.completions.create(
            model=GROQ_MODEL,
            messages=[
                {"role": "system", "content": SYSTEM_PROMPT},
                {
                    "role": "user",
                    "content": (
                        f"داده‌های بازار در این لحظه:\n{market_context}\n\n"
                        f"سوال کاربر:\n{user_question}"
                    ),
                },
            ],
            temperature=0.4,
            max_tokens=700,
        )
        return completion.choices[0].message.content.strip()
    except Exception:
        logger.exception("خطا در تماس با Groq API")
        return (
            "متأسفانه در حال حاضر امکان دریافت پاسخ از مشاور هوشمند نیست. "
            "لطفاً کمی بعد دوباره تلاش کنید."
        )
