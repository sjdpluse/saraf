import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const read=path=>readFileSync(new URL('../../'+path,import.meta.url),'utf8');
const admin=read('supabase/functions/saraf-original-admin/index.ts');
const sql=read('supabase/sql/saraf_original_admin_commands_STAGED.sql');
const ui=read('webapp/src/pages/OriginalAdmin.jsx');
const bridge=read('webapp/src/lib/originalAdminBridge.js');
const kyc=read('supabase/functions/saraf-legacy-kyc/index.ts');
const canonical=read('supabase/functions/saraf-telegram-bridge/index.ts');
test('original KYC approval is HMAC+private admin allowlist+write switch, never public',()=>{
 assert.match(admin,/verifyTelegramInitData/);
 assert.match(admin,/if\(!isOwner\(actor\.id\)\)/);
 assert.match(admin,/action==='kyc\.review'/);
 assert.match(admin,/if\(isWrite\(action\)&&!WRITE\)/);
 assert.match(admin,/saraf_original_admin_review_kyc/);
 assert.match(sql,/CREATE OR REPLACE FUNCTION public\.saraf_original_admin_review_kyc/);
 assert.match(sql,/LANGUAGE plpgsql SECURITY INVOKER/);
 assert.match(sql,/REVOKE ALL ON FUNCTION public\.saraf_original_admin_review_kyc/);
 assert.match(sql,/GRANT EXECUTE ON FUNCTION public\.saraf_original_admin_review_kyc/);
 assert.match(sql,/TO service_role/);
 assert.match(sql,/WHERE chat_id=p_chat_id FOR UPDATE/);
 assert.match(sql,/v_profile\.kyc_status<>'pending'/);
 assert.match(sql,/v_profile\.id_document_path/);
 assert.match(sql,/v_profile\.selfie_path/);
 assert.match(sql,/INSERT INTO public\.audit_log/);
});
test('original signed KYC admin inbox shows only 90-second private ID and selfie URLs',()=>{
 assert.match(admin,/if\(action==='kyc\.pending'\)/);
 assert.match(admin,/\.eq\('kyc_status','pending'\)/);
 assert.match(admin,/\.createSignedUrl\(row\.id_document_path,90\)/);
 assert.match(admin,/\.createSignedUrl\(row\.selfie_path,90\)/);
 assert.match(admin,/id_url:id\.error\?null/);
 assert.match(admin,/selfie_url:selfie\.error\?null/);
 assert.match(ui,/customer\.id_url/);
 assert.match(ui,/customer\.selfie_url/);
 assert.match(ui,/referrerPolicy="no-referrer"/);
 assert.match(ui,/reviewKyc\(customer\.chat_id,'verify'\)/);
 assert.match(ui,/reviewKyc\(customer\.chat_id,'reject'\)/);
 assert.match(bridge,/'kyc\.pending','kyc\.review'/);
});
test('original KYC uploads always require configured reviewer and server feature flag',()=>{
 assert.match(kyc,/if\(!ENABLED\)return answer\(origin,503/);
 assert.match(kyc,/if\(!ADMIN_IDS\.length\)/);
 assert.match(kyc,/KYC_ADMIN_REVIEW_NOT_CONFIGURED/);
 assert.match(kyc,/SARAF_ADMIN_CHAT_IDS/);
 assert.match(canonical,/identity_uploads_enabled:/);
 assert.match(canonical,/SARAF_ORIGINAL_KYC_ENABLED/);
});
